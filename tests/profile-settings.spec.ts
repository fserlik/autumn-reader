test("avatar uploads PNG when the WebView cannot encode WebP", async ({page,context}) => {
  const cloud = await mockCloud(page,true);
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.toBlob;
    HTMLCanvasElement.prototype.toBlob = function(callback, type, quality) {
      return original.call(this,callback,type === "image/webp" ? "image/png" : type,quality);
    };
  });
  await page.goto("/"); await login(page);
  await page.locator('.nav-button[data-view="profile"]').click();
  await page.locator("#profile-edit").click();
  await page.locator('#profile-form [name="avatar"]').setInputFiles("src/assets/autumn-leaf.png");
  await expect(page.locator("#profile-form .avatar-preview")).toBeVisible();
  await page.locator('#profile-form button[type="submit"]').click();
  await expect(page.locator("#profile-editor")).toBeHidden();
  expect(cloud.avatarUploads[0].contentType).toBe("image/png");
  expect(cloud.avatarUploads[0].size).toBeLessThanOrEqual(512*1024);
  await context.setOffline(true); await page.reload();
  await expect.poll(() => page.locator("#profile-photo").evaluate((image:HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0);
});
