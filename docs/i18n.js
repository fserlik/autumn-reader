window.autumnI18n = {
  lang: "en",
  t(key) { return translations[this.lang]?.[key] ?? key; },
  apply(lang) {
    if (!translations[lang]) lang = "en";
    this.lang = lang; localStorage.setItem("autumn-reader-language", lang); document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(el => { const value=this.t(el.dataset.i18n); if(value!==el.dataset.i18n) el.textContent=value; });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(el => el.setAttribute("aria-label",this.t(el.dataset.i18nAriaLabel)));
    const meta=document.querySelector('[data-i18n-content="meta.description"]'); if(meta) meta.content=this.t("meta.description");
    document.title=this.t("meta.title");
    document.querySelectorAll("[data-lang]").forEach(btn=>btn.setAttribute("aria-pressed",String(btn.dataset.lang===lang)));
    document.dispatchEvent(new CustomEvent("autumn-language-change",{detail:{lang}}));
  }
};
document.addEventListener("DOMContentLoaded",()=>{ document.querySelectorAll("[data-lang]").forEach(btn=>btn.addEventListener("click",()=>window.autumnI18n.apply(btn.dataset.lang))); window.autumnI18n.apply(localStorage.getItem("autumn-reader-language") || "en"); });
